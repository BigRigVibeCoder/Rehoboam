//! CLI tool to generate and verify terrain_v0 golden digests (SPR-033 T-03).
//!
//! Generates or verifies the L0 and L1 XXH3-128 content digests of `hamlet`'s
//! settlement-1 bubble (90 m).
//!
//! Usage:
//!   cargo run --bin terrain_golden -- --check
//!   cargo run --bin terrain_golden -- --write

#![forbid(unsafe_code)]
#![deny(clippy::float_arithmetic)]
#![allow(
    clippy::pedantic,
    clippy::unwrap_used,
    clippy::expect_used,
    clippy::panic,
    clippy::disallowed_methods,
    clippy::disallowed_types,
    reason = "CLI entrypoint error handling, argument parsing and exit status"
)]

use std::collections::BTreeMap;
use std::env;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::exit;

use rh_view_core::digest::{BubbleDef, compute_content_digest};
use rh_view_core::export::WorldgenExport;
use rh_view_core::terrain::{GENERATOR_VERSION, TerrainContext};

fn find_repo_root() -> PathBuf {
    let manifest_dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    manifest_dir.join("../..").canonicalize().unwrap()
}

fn ensure_hamlet_export(root: &Path) -> PathBuf {
    let export_dir = root.join("target/viewer/exports");
    let hamlet_toml = export_dir.join("hamlet.toml");
    assert!(
        hamlet_toml.exists(),
        "hamlet export not found at {}: run export_worldgen_lite.py --world hamlet first",
        hamlet_toml.display()
    );
    export_dir
}

fn parse_golden_file(path: &Path) -> BTreeMap<String, String> {
    let content = fs::read_to_string(path)
        .unwrap_or_else(|e| panic!("failed to read golden file {}: {e}", path.display()));
    let mut map = BTreeMap::new();
    for line in content.lines() {
        let trimmed = line.trim();
        if trimmed.is_empty() || trimmed.starts_with('#') {
            continue;
        }
        let mut parts = trimmed.split_whitespace();
        if let Some(key) = parts.next() {
            let val = parts.collect::<Vec<_>>().join(" ");
            map.insert(key.to_string(), val);
        }
    }
    map
}

fn main() {
    let args: Vec<String> = env::args().collect();
    let write_mode = args.iter().any(|a| a == "--write");
    let check_mode = args.iter().any(|a| a == "--check") || !write_mode;

    let root = find_repo_root();
    let export_dir = ensure_hamlet_export(&root);
    let export = WorldgenExport::load_from_dir(&export_dir, "hamlet")
        .unwrap_or_else(|e| panic!("failed to load hamlet export: {e}"));

    let ctx = TerrainContext::new(&export);

    // Settlement 1 bubble: centre (13585, 1026, 6042), radius 90m
    let bubble = BubbleDef {
        focus_settlement: 1,
        centre: [13585, 1026, 6042],
        radius: 90,
    };

    let mesh_200_mode = args.iter().any(|a| a == "--mesh-200");
    if mesh_200_mode {
        let mut mesher = binary_greedy_meshing::Mesher::<{ rh_view_core::chunk::CS }>::new();
        let mut count = 0;
        'outer: for dx in -10..=10 {
            for dz in -10..=10 {
                for dy in 10..25 {
                    let coord = rh_view_core::chunk::ChunkCoord {
                        level: 0,
                        x: 218 + dx,
                        y: dy,
                        z: 97 + dz,
                    };
                    let chunk = ctx.generate_chunk(coord);
                    if !chunk.is_interior_all_air() {
                        let _m = rh_view_core::mesh::mesh_chunk(&chunk, &mut mesher);
                        count += 1;
                        if count == 200 {
                            break 'outer;
                        }
                    }
                }
            }
        }
        println!("MESH-200: meshed {count} terrain chunks");
        return;
    }

    let l0_chunks = ctx.generate_bubble_chunks(&bubble, 0);
    let l0_digest = compute_content_digest(GENERATOR_VERSION, &bubble, &l0_chunks);

    let l1_chunks = ctx.generate_bubble_chunks(&bubble, 1);
    let l1_digest = compute_content_digest(GENERATOR_VERSION, &bubble, &l1_chunks);

    let golden_path = root.join("viewer/golden/terrain_v0.txt");

    if write_mode {
        if let Some(parent) = golden_path.parent() {
            fs::create_dir_all(parent).unwrap();
        }
        let lines = [
            "# terrain_v0 golden digests (SPR-033 T-03): GENERATED by".to_string(),
            "# cargo run --bin terrain_golden -- --write; do not edit.".to_string(),
            format!("version {GENERATOR_VERSION}"),
            "world hamlet".to_string(),
            "settlement 1".to_string(),
            format!(
                "centre {} {} {}",
                bubble.centre[0], bubble.centre[1], bubble.centre[2]
            ),
            format!("radius {}", bubble.radius),
            format!("l0_chunks {}", l0_chunks.len()),
            format!("l0_digest {l0_digest}"),
            format!("l1_chunks {}", l1_chunks.len()),
            format!("l1_digest {l1_digest}"),
        ];
        let content = lines.join("\n") + "\n";
        fs::write(&golden_path, content).unwrap();
        println!(
            "TERRAIN-GOLDEN: wrote {} (L0: {} chunks, L1: {} chunks) to {}",
            GENERATOR_VERSION,
            l0_chunks.len(),
            l1_chunks.len(),
            golden_path.display()
        );
        return;
    }

    if check_mode {
        if !golden_path.exists() {
            eprintln!("FAIL: golden file {} does not exist", golden_path.display());
            exit(1);
        }
        let golden = parse_golden_file(&golden_path);
        let golden_version = golden.get("version").map(String::as_str).unwrap_or("");
        if golden_version != GENERATOR_VERSION {
            eprintln!(
                "STALE: version mismatch: golden has '{golden_version}', generator is '{GENERATOR_VERSION}'"
            );
            exit(1);
        }

        let expected_l0 = golden.get("l0_digest").map(String::as_str).unwrap_or("");
        if expected_l0 != l0_digest {
            eprintln!(
                "STALE: l0_digest mismatch for version {GENERATOR_VERSION}:\n  expected: {expected_l0}\n  computed: {l0_digest}"
            );
            exit(1);
        }

        let expected_l1 = golden.get("l1_digest").map(String::as_str).unwrap_or("");
        if expected_l1 != l1_digest {
            eprintln!(
                "STALE: l1_digest mismatch for version {GENERATOR_VERSION}:\n  expected: {expected_l1}\n  computed: {l1_digest}"
            );
            exit(1);
        }

        println!(
            "TERRAIN-GOLDEN: PASS (L0: {} chunks [{l0_digest}], L1: {} chunks [{l1_digest}])",
            l0_chunks.len(),
            l1_chunks.len()
        );
    }
}
